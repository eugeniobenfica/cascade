"""Writes src/text/joiningData.inc: the Unicode Joining_Type of every code point, as ranges.

    python tools/genArabicJoining.py path/to/ArabicShaping.txt

ArabicShaping.txt is the Unicode Character Database's (https://www.unicode.org/Public/<version>/ucd/ArabicShaping.txt),
of the same version as this Python's unicodedata: the code points it does not list are T (transparent) when their
general category is Mn, Me or Cf, U (non-joining) otherwise, as it says.
"""
import os
import sys
import unicodedata

TYPES = {"U": "U", "R": "R", "L": "L", "D": "D", "C": "C", "T": "T"}


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 1
    jt = [None] * 0x110000
    with open(sys.argv[1], encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = [x.strip() for x in line.split(";")]
            jt[int(parts[0], 16)] = parts[2]
    for cp in range(0x110000):
        if jt[cp] is None:
            jt[cp] = "T" if unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf") else "U"
    ranges = []
    start, cur = 0, jt[0]
    for cp in range(1, 0x110000):
        if jt[cp] != cur:
            ranges.append((start, cp - 1, cur))
            start, cur = cp, jt[cp]
    ranges.append((start, 0x10FFFF, cur))
    listed = [r for r in ranges if r[2] != "U"]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "src", "text", "joiningData.inc")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/genArabicJoining.py from Unicode %s: do not edit. */\n" % unicodedata.unidata_version)
        f.write("/* {first, last, Joining_Type}: the code points not listed are U (non-joining). */\n")
        for a, b, t in listed:
            f.write("{0x%X, 0x%X, JT_%s},\n" % (a, b, TYPES[t]))
    print("%s: %d ranges (Unicode %s)" % (out, len(listed), unicodedata.unidata_version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
