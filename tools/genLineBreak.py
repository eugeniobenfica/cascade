"""Writes src/text/lineBreakData.inc: the Unicode line breaking class of every code point (UAX #14), as ranges.

    python tools/genLineBreak.py path/to/LineBreak.txt

LineBreak.txt is the Unicode Character Database's (https://www.unicode.org/Public/<version>/ucd/LineBreak.txt), of
the same version as this Python's unicodedata, which gives the rest: the East Asian width and the general category.
The classes are resolved as rule LB1 resolves them (AI, SG and XX are AL; SA is CM for the nonspacing and spacing
marks, AL otherwise; CJ is NS). With each class, flags for the rules that look past it:
    1  East Asian: East_Asian_Width F, W or H (LB19a, LB30)
    2  an initial quotation mark (\\p{Pi}: LB15a, LB19)
    4  a final quotation mark (\\p{Pf}: LB15b, LB19)
    8  an unassigned code point that is Extended_Pictographic (LB30b: those of U+1F000..U+1FFFD)
"""
import os
import sys
import unicodedata

CLASSES = ["AL", "BK", "CR", "LF", "NL", "SP", "ZW", "ZWJ", "CM", "WJ", "GL", "BA", "BB", "HY", "HH", "CB", "CL", "CP",
           "EX", "IN", "NS", "OP", "QU", "IS", "NU", "PO", "PR", "SY", "EB", "EM", "H2", "H3", "HL", "ID", "JL", "JV",
           "JT", "RI", "AK", "AP", "AS", "VF", "VI", "B2"]


def read(path):
    cls = ["XX"] * 0x110000
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            cps, c = [x.strip() for x in line.split(";")]
            a, _, b = cps.partition("..")
            for cp in range(int(a, 16), int(b or a, 16) + 1):
                cls[cp] = c
    return cls


def resolve(cp, c):
    if c in ("AI", "SG", "XX"):
        return "AL"
    if c == "SA":
        return "CM" if unicodedata.category(chr(cp)) in ("Mn", "Mc") else "AL"
    if c == "CJ":
        return "NS"
    return c


def flags(cp):
    ch = chr(cp)
    f = 0
    if unicodedata.east_asian_width(ch) in ("F", "W", "H"):
        f |= 1
    gc = unicodedata.category(ch)
    if gc == "Pi":
        f |= 2
    if gc == "Pf":
        f |= 4
    if gc == "Cn" and 0x1F000 <= cp <= 0x1FFFD:
        f |= 8
    return f


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 1
    raw = read(sys.argv[1])
    ranges = []
    start, cur = 0, (resolve(0, raw[0]), flags(0))
    for cp in range(1, 0x110000):
        v = (resolve(cp, raw[cp]), flags(cp))
        if v != cur:
            ranges.append((start, cp - 1, cur))
            start, cur = cp, v
    ranges.append((start, 0x10FFFF, cur))
    listed = [r for r in ranges if r[2] != ("AL", 0)]
    for r in listed:
        assert r[2][0] in CLASSES, r
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "src", "text", "lineBreakData.inc")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/genLineBreak.py from Unicode %s: do not edit. */\n" % unicodedata.unidata_version)
        f.write("/* {first, last, class, flags}: the code points not listed are AL, with no flags. */\n")
        for a, b, (c, fl) in listed:
            f.write("{0x%X, 0x%X, LB_%s, %d},\n" % (a, b, c, fl))
    print("%s: %d ranges (Unicode %s)" % (out, len(listed), unicodedata.unidata_version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
