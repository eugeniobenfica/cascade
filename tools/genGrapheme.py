"""Writes src/text/graphemeData.inc: what Unicode's grapheme cluster boundaries (UAX #29) need of every code point.

    python tools/genGrapheme.py GraphemeBreakProperty.txt emoji-data.txt DerivedCoreProperties.txt

The three files are the Unicode Character Database's, of one version (https://www.unicode.org/Public/<version>/ucd/:
auxiliary/GraphemeBreakProperty.txt, emoji/emoji-data.txt, DerivedCoreProperties.txt). Each range has the
Grapheme_Cluster_Break value and flags:
    1  Extended_Pictographic (GB11)
    2  Indic_Conjunct_Break=Consonant, 4  =Linker, 8  =Extend (GB9c)
"""
import os
import re
import sys

VALUES = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark", "L", "V", "T",
          "LV", "LVT"]
NAMES = {"Other": "OTHER", "CR": "CR", "LF": "LF", "Control": "CONTROL", "Extend": "EXTEND", "ZWJ": "ZWJ",
         "Regional_Indicator": "RI", "Prepend": "PREPEND", "SpacingMark": "SPACING_MARK", "L": "L", "V": "V", "T": "T",
         "LV": "LV", "LVT": "LVT"}


def ranges(path):
    """(first, last, fields after the code points) of each line"""
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = [x.strip() for x in line.split(";")]
            a, _, b = parts[0].partition("..")
            yield int(a, 16), int(b or a, 16), parts[1:]


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        return 1
    gcb = ["Other"] * 0x110000
    flags = [0] * 0x110000
    for a, b, f in ranges(sys.argv[1]):
        for cp in range(a, b + 1):
            gcb[cp] = f[0]
    for a, b, f in ranges(sys.argv[2]):
        if f[0] == "Extended_Pictographic":
            for cp in range(a, b + 1):
                flags[cp] |= 1
    incb = {"Consonant": 2, "Linker": 4, "Extend": 8}
    for a, b, f in ranges(sys.argv[3]):
        if f[0] == "InCB":
            for cp in range(a, b + 1):
                flags[cp] |= incb[f[1]]
    version = "?"
    with open(sys.argv[1], encoding="utf-8") as f:
        m = re.search(r"GraphemeBreakProperty-([0-9.]+)\.txt", f.readline())
        if m:
            version = m.group(1)
    out_ranges = []
    start, cur = 0, (gcb[0], flags[0])
    for cp in range(1, 0x110000):
        v = (gcb[cp], flags[cp])
        if v != cur:
            out_ranges.append((start, cp - 1, cur))
            start, cur = cp, v
    out_ranges.append((start, 0x10FFFF, cur))
    listed = [r for r in out_ranges if r[2] != ("Other", 0)]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "src", "text", "graphemeData.inc")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/genGrapheme.py from Unicode %s: do not edit. */\n" % version)
        f.write("/* {first, last, Grapheme_Cluster_Break, flags}: the code points not listed are Other, with no flags. */\n")
        for a, b, (g, fl) in listed:
            f.write("{0x%X, 0x%X, GB_%s, %d},\n" % (a, b, NAMES[g], fl))
    print("%s: %d ranges (Unicode %s)" % (out, len(listed), version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
