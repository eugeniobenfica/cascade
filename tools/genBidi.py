"""Writes src/text/bidiData.inc: the Unicode bidirectional class of every code point, as ranges.

    python tools/genBidi.py

Run it again (with a newer Python) to follow a newer Unicode version. The classes come from
Python's unicodedata; unassigned code points take the defaults of DerivedBidiClass.txt (R or AL
in the right-to-left blocks, ET for the currency symbols block, BN for noncharacters and default
ignorables, L elsewhere).
"""
import os
import sys
import unicodedata

CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
           "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]

# Defaults for unassigned code points (DerivedBidiClass.txt, @missing lines).
DEFAULTS = [
    (0x0600, 0x07BF, "AL"), (0x07C0, 0x085F, "R"), (0x0860, 0x08FF, "AL"),
    (0x20A0, 0x20CF, "ET"),
    (0xFB1D, 0xFB4F, "R"), (0xFB50, 0xFDCF, "AL"), (0xFDF0, 0xFDFF, "AL"), (0xFE70, 0xFEFF, "AL"),
    (0x10800, 0x10CFF, "R"), (0x10D00, 0x10D3F, "AL"), (0x10D40, 0x10EBF, "R"), (0x10EC0, 0x10EFF, "AL"),
    (0x10F00, 0x10F2F, "R"), (0x10F30, 0x10F6F, "AL"), (0x10F70, 0x10FFF, "R"),
    (0x1E800, 0x1EC6F, "R"), (0x1EC70, 0x1ECBF, "AL"), (0x1ECC0, 0x1ECFF, "R"), (0x1ED00, 0x1ED4F, "AL"),
    (0x1ED50, 0x1EDFF, "R"), (0x1EE00, 0x1EEFF, "AL"), (0x1EF00, 0x1EFFF, "R"),
    (0xFDD0, 0xFDEF, "BN"), (0xFFF0, 0xFFF8, "BN"), (0xE0000, 0xE0FFF, "BN"),
]


def bidi_class(cp):
    c = unicodedata.bidirectional(chr(cp))
    if c:
        return c
    if (cp & 0xFFFE) == 0xFFFE:
        return "BN"
    for a, b, d in DEFAULTS:
        if a <= cp <= b:
            return d
    return "L"


def main():
    ranges = []
    start, cur = 0, bidi_class(0)
    for cp in range(1, 0x110000):
        c = bidi_class(cp)
        if c != cur:
            ranges.append((start, cp - 1, cur))
            start, cur = cp, c
    ranges.append((start, 0x10FFFF, cur))
    # L is what is not listed
    listed = [r for r in ranges if r[2] != "L"]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "src", "text", "bidiData.inc")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/genBidi.py from Unicode %s: do not edit. */\n" % unicodedata.unidata_version)
        f.write("/* {first, last, class}: the code points not listed are L. */\n")
        for a, b, c in listed:
            f.write("{0x%X, 0x%X, CSCD_BIDI_%s},\n" % (a, b, c))
    print("%s: %d ranges (Unicode %s)" % (out, len(listed), unicodedata.unidata_version))


if __name__ == "__main__":
    sys.exit(main())
