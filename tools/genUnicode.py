"""Writes src/text/unicodeData.inc: the Unicode properties the shaper needs, as sorted ranges.

    python tools/genUnicode.py path/to/emoji-data.txt

emoji-data.txt is the Unicode Character Database's (https://www.unicode.org/Public/<version>/ucd/emoji/);
take the version Python's unicodedata has (python -c "import unicodedata; print(unicodedata.unidata_version)").

- kEmojiPresentation: Emoji_Presentation (shown as color emoji unless U+FE0E follows)
- kPictographic: Extended_Pictographic (may start an emoji sequence, or be one with U+FE0F)
- kMarks: the combining marks (general categories Mn, Mc, Me), which stay in their base's font
"""
import os
import sys
import unicodedata


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def emoji_property(path, name):
    cps = set()
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        span, prop = [p.strip() for p in line.split(";")]
        if prop != name:
            continue
        a, _, b = span.partition("..")
        for cp in range(int(a, 16), int(b or a, 16) + 1):
            cps.add(cp)
    return cps


def table(name, rs):
    body = ",\n".join("    {0x%X, 0x%X}" % (a, b) for a, b in rs)
    return "static const uint32_t %s[][2] = {\n%s\n};\n" % (name, body)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = sys.argv[1]
    marks = [cp for cp in range(0x110000) if unicodedata.category(chr(cp)) in ("Mn", "Mc", "Me")]
    out = ["/* Generated by tools/genUnicode.py from Unicode %s: do not edit. */\n" % unicodedata.unidata_version,
           table("kEmojiPresentation", ranges(emoji_property(data, "Emoji_Presentation"))),
           table("kPictographic", ranges(emoji_property(data, "Extended_Pictographic"))),
           table("kMarks", ranges(marks))]
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "text", "unicodeData.inc")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out))


main()
