"""Writes a libabigail suppression file that keeps only the functions and variables include/cascade declares.

The engine's shared library exports every function (its tests reach the library's own); CI's ABI job (linux.yml) gives
this file to abidw and abidiff so that what the headers do not declare is left out of the comparison, and an internal
function that goes or changes is no break.
    python3 tools/abiPublic.py > public.supp
    python3 tools/abiPublic.py --without NAME in.abi out.abi   (the job's own check: the ABI without that function)
"""
import glob
import os
import re
import sys
import xml.etree.ElementTree as ET

if len(sys.argv) == 5 and sys.argv[1] == "--without":
    name, src, dst = sys.argv[2:]
    tree = ET.parse(src)
    gone = 0
    for parent in tree.iter():
        for child in list(parent):
            if child.tag in ("elf-symbol", "function-decl") and child.get("name") == name:
                parent.remove(child)
                gone += 1
    if not gone:
        sys.exit("%s: not in %s" % (name, src))
    tree.write(dst)
    sys.exit(0)

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = set()
for path in sorted(glob.glob(os.path.join(root, "include", "cascade", "*.h"))):
    text = open(path, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    # (a declaration: a name then its parameters; the static inline ones are not in the library, and harmless here)
    names.update(re.findall(r"\b(cscd[A-Z_]\w*)\s*\(", text))
    # (variables: extern ones)
    names.update(re.findall(r"\bextern\b[^;(]*?\b(cscd\w+)\s*(?:\[[^\]]*\])?\s*;", text))
alternatives = "|".join(sorted(names))
print("# generated by tools/abiPublic.py: only what include/cascade declares")
print("[suppress_function]")
print("  symbol_name_not_regexp = ^(%s)$" % alternatives)
print("  drop = yes")
print("[suppress_variable]")
print("  symbol_name_not_regexp = ^(%s)$" % alternatives)
print("  drop = yes")
