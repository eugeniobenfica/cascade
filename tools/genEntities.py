"""Writes src/dom/htmlEntities.inc: HTML's named character references (all 2,231 of them, with the legacy ones that may
come without a semicolon), from Python's html.entities.html5, which is the specification's table.
    python3 tools/genEntities.py
"""
import html.entities
import os


def c_string(s):
    out = []
    for b in s.encode("utf-8"):
        if 32 <= b < 127 and chr(b) not in '"\\?':
            out.append(chr(b))
        else:
            out.append("\\x%02X" % b)
    # (a hex escape followed by a hex digit would run on: split the literal there)
    text = ""
    for i, piece in enumerate(out):
        if i and out[i - 1].startswith("\\x") and len(piece) == 1 and piece in "0123456789abcdefABCDEF":
            text += '" "'
        text += piece
    return '"%s"' % text


def main():
    names = sorted(html.entities.html5.items())
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    lines = ["/* Generated by tools/genEntities.py from the HTML specification's named character references: do not edit. */",
             "/* each: the name after the &, with its semicolon when it has one (a few legacy ones also come without), then the",
             " * text it stands for (UTF-8) */"]
    for name, value in names:
        lines.append("{%s, %s}," % (c_string(name), c_string(value)))
    with open(os.path.join(root, "src", "dom", "htmlEntities.inc"), "w", encoding="utf-8", newline="") as f:
        f.write("".join(line + "\n" for line in lines))
    print("%d names" % len(names))


if __name__ == "__main__":
    main()
